const dictionaries = { vi, en }
export type TKey = keyof typeof vi
export type T = (key: TKey | string, vars?: Record<string, string | number>) => string

type I18n = { lang: Lang; setLang: (lang: Lang) => void; t: T; has: (key: string) => boolean }
const I18nContext = createContext<I18n | null>(null)

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('qit_lang')
    if (saved === 'vi' || saved === 'en') return saved
  } catch { /* storage unavailable */ }
  return navigator.language?.toLowerCase().startsWith('vi') ? 'vi' : 'en'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang)
  useEffect(() => { document.documentElement.lang = lang }, [lang])

  const setLang = useCallback((next: Lang) => {
    setLangState(next)
    try { localStorage.setItem('qit_lang', next) } catch { /* storage unavailable */ }
  }, [])

  const value = useMemo<I18n>(() => {
    const dict = dictionaries[lang] as Record<string, string>
    return {
      lang,
      setLang,
      has: key => key in dict,
      // Unknown keys fall back to the key itself, so data values (e.g. a custom topic) pass through.
      t: (key, vars) => {
        let text = dict[key] ?? key
        if (vars) for (const [name, value] of Object.entries(vars)) text = text.replace(`{${name}}`, String(value))
        return text
      },
    }
  }, [lang, setLang])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18n {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider')
  return ctx
}

/** Translate a data value such as a category name; unknown values are shown as they are. */
export function label(i18n: I18n, prefix: string, value: string | null | undefined): string {
  if (!value) return ''
  const key = `${prefix}.${value}`
  return i18n.has(key) ? i18n.t(key) : value
}

export function formatDate(value: string, lang: Lang, withTime = false): string {
  const date = new Date(value)
  const locale = lang === 'vi' ? 'vi-VN' : 'en-GB'
  return withTime
    ? date.toLocaleString(locale, { day: '2-digit', month: '2-digit', year: 'numeric', hour: '2-digit', minute: '2-digit' })
    : date.toLocaleDateString(locale, { day: '2-digit', month: '2-digit', year: 'numeric' })
}
